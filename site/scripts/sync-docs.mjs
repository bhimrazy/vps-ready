// Generates Starlight pages from the repo's docs/*.md, which stay the single
// source of truth. Each page gets frontmatter from its H1, relative links are
// rewritten to site routes (other docs) or GitHub URLs (anything else), and
// mermaid fences become <pre class="mermaid"> for client-side rendering.
// It also renders the audit controls catalog (src/audit/controls/*.toml) as
// the Security controls reference, and copies the repo logos and screenshots.
// Output paths are gitignored; run via `npm run build` or `npm run dev`.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..');
const BASE = '';
const REPO_URL = 'https://github.com/bhimrazy/vps-ready';

// docs/<file> -> route under /docs/, with its sidebar label.
// Every docs/*.md must be listed so a new doc can't be silently left out.
// `note` is an aside put above the page, for docs that read as user guidance
// but describe more than what ships.
// `order` sorts the autogenerated sidebar groups.
const PAGES = {
  'security-baseline.md': {
    slug: 'reference/security-baseline',
    label: 'Security baseline',
    order: 4,
    note: 'This is the design spec behind every module, including modules and distros that are planned but not built yet. What ships today is in [Profiles and modules](/docs/guides/profiles-and-modules/).',
  },
  'architecture.md': { slug: 'project/architecture', label: 'Architecture', order: 1 },
  'decisions.md': { slug: 'project/decisions', label: 'Decisions', order: 2 },
  'scope.md': { slug: 'project/scope', label: 'Vision and scope', order: 3 },
  'testing.md': { slug: 'project/testing', label: 'Testing', order: 4 },
  'release.md': { slug: 'project/release', label: 'Supply chain and release', order: 5 },
  'm2-plan.md': { slug: 'project/m2-plan', label: 'Design notes: M2', order: 6 },
  'm3-plan.md': { slug: 'project/m3-plan', label: 'Design notes: M3', order: 7 },
};
const DOCS_OUT = join(site, 'src/content/docs/docs');
const CONTROLS_SLUG = 'reference/security-controls';
// Wholly generated directories, emptied first so a renamed doc leaves nothing behind.
const OUT_DIRS = ['project'].map((d) => join(DOCS_OUT, d));

const docsDir = join(repo, 'docs');
const files = readdirSync(docsDir).filter((f) => f.endsWith('.md'));
const unmapped = files.filter((f) => !PAGES[f]);
if (unmapped.length) {
  console.error(`sync-docs: add these to PAGES in scripts/sync-docs.mjs: ${unmapped.join(', ')}`);
  process.exit(1);
}

for (const d of OUT_DIRS) rmSync(d, { recursive: true, force: true });

// Resolves a link target written relative to docs/ (or the repo root for README).
function rewrite(target, fromDir, isImage) {
  if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return target;
  const [path, hash = ''] = target.split(/(?=#)/);
  const repoPath = posix.normalize(posix.join(fromDir, path));
  const name = repoPath.startsWith('docs/') ? repoPath.slice(5) : null;
  if (name && PAGES[name]) return `${BASE}/docs/${PAGES[name].slug}/${hash}`;
  if (isImage) return `https://raw.githubusercontent.com/bhimrazy/vps-ready/main/${repoPath}`;
  return `${REPO_URL}/blob/main/${repoPath}${hash}`;
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function plain(md) {
  return md
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*_>]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function transform(src, file) {
  const lines = src.split('\n');
  const h1 = lines.findIndex((l) => l.startsWith('# '));
  if (h1 === -1) throw new Error(`${file}: no H1`);
  const title = lines[h1].slice(2).trim();
  let body = lines.slice(h1 + 1).join('\n');

  // Mermaid fences; everything else keeps its fence.
  body = body.replace(/^```mermaid\n([\s\S]*?)^```$/gm, (_, code) => `<pre class="mermaid">${escapeHtml(code)}</pre>`);

  // Shiki calls GitHub's `sshconfig` fence language `ssh-config`.
  body = body.replace(/^```sshconfig$/gm, '```ssh-config');

  // Rewrite links outside fenced code only.
  const parts = body.split(/(^```[\s\S]*?^```$)/m);
  body = parts
    .map((part, i) =>
      i % 2
        ? part
        : part.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)\)/g, (_, bang, text, target) =>
            `${bang}[${text}](${rewrite(target, 'docs', bang === '!')})`,
          ),
    )
    .join('');

  const firstPara = body.split(/\n\s*\n/).map((p) => p.trim()).find((p) => p && /^[A-Za-z*`]/.test(p));
  const description = firstPara ? plain(firstPara).slice(0, 200).replace(/\s\S*$/, '') : '';
  const page = PAGES[file];
  if (page.note) body = `\n:::note\n${page.note}\n:::\n${body}`;
  const fm = [
    '---',
    `title: ${JSON.stringify(title)}`,
    description && `description: ${JSON.stringify(description)}`,
    `sidebar:\n  label: ${JSON.stringify(page.label)}\n  order: ${page.order}`,
    `editUrl: ${JSON.stringify(`${REPO_URL}/edit/main/docs/${file}`)}`,
    '---',
    '',
    `<!-- Generated from docs/${file} by scripts/sync-docs.mjs. Edit the source, not this file. -->`,
  ];
  return fm.filter(Boolean).join('\n') + '\n' + body.replace(/^\n+/, '\n');
}

for (const file of files) {
  const out = join(DOCS_OUT, `${PAGES[file].slug}.md`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, transform(readFileSync(join(docsDir, file), 'utf8'), file));
}

// The controls catalog: one table per area file, in the order audit groups them.
const AREAS = [
  ['ssh.toml', 'SSH server'],
  ['firewall.toml', 'Firewall'],
  ['kernel.toml', 'Kernel'],
  ['network.toml', 'Network'],
  ['updates.toml', 'Updates'],
  ['mac.toml', 'Mandatory access control'],
];
const controlsDir = join(repo, 'crates/vps-ready/src/audit/controls');
const areaFiles = readdirSync(controlsDir).filter((f) => f.endsWith('.toml'));
const unlisted = areaFiles.filter((f) => !AREAS.some(([a]) => a === f));
if (unlisted.length) {
  console.error(`sync-docs: add these to AREAS in scripts/sync-docs.mjs: ${unlisted.join(', ')}`);
  process.exit(1);
}

// Only the flat `key = "string"` lines are read; `check` is left to the binary.
function parseControls(text) {
  return text
    .split(/^\[\[control\]\]$/m)
    .slice(1)
    .map((block) => {
      const c = {};
      for (const [, key, value] of block.matchAll(/^(id|severity|title|why|fix) = "(.*)"$/gm)) c[key] = value;
      return c;
    });
}

const cell = (s) => s.replace(/\|/g, '\\|');
let total = 0;
const sections = AREAS.map(([file, name]) => {
  const src = readFileSync(join(controlsDir, file), 'utf8');
  // The file's header comment says where its checks read from.
  const header = src.slice(0, src.search(/^[^#]/m)).replace(/^#\s?/gm, '').replace(/\s+/g, ' ');
  const intro = header.match(/Checks? [^.]*\./)?.[0] ?? '';
  const controls = parseControls(src);
  total += controls.length;
  const rows = controls.map(
    (c) =>
      `| \`${c.id}\`<br/>${c.severity} | **${cell(c.title)}**<br/>${cell(c.why)}<br/>Fixed by ${c.fix ? `\`${c.fix}\`` : 'no module yet'} |`,
  );
  return [`## ${name}`, '', intro, '', '| Control | What it checks and why |', '|---|---|', ...rows].join('\n');
});
const controlsPage = [
  '---',
  'title: Security controls',
  'sidebar:\n  order: 2',
  `description: ${JSON.stringify(`Every control vps-ready audit checks: its stable ID, severity, why it matters and the module that fixes it.`)}`,
  `editUrl: ${JSON.stringify(`${REPO_URL}/tree/main/crates/vps-ready/src/audit/controls`)}`,
  '---',
  '',
  '<!-- Generated from crates/vps-ready/src/audit/controls/*.toml by scripts/sync-docs.mjs. -->',
  '',
  `A control is one thing \`vps-ready audit\` checks. There are ${total}, each with a stable ID you can track in CI, a severity, and the reason it matters. When a module can fix a failed control, \`audit\` prints the command under it, for example \`fix: sudo vps-ready apply --module ssh.server\`.`,
  '',
  'Each control ends as one of four outcomes: **pass**, **fail** (with the value found), **unknown** (the fact could not be read, usually without root) or **skip** (not checked here, for example kernel settings inside a container). Unknown never counts as a pass: `audit` exits 0 only when no control fails or is unknown.',
  '',
  ...sections.flatMap((s) => [s, '']),
  `The catalog lives in [\`crates/vps-ready/src/audit/controls\`](${REPO_URL}/tree/main/crates/vps-ready/src/audit/controls), one TOML file per area, so you can review it without reading Rust.`,
  '',
].join('\n');
mkdirSync(join(DOCS_OUT, 'reference'), { recursive: true });
writeFileSync(join(DOCS_OUT, `${CONTROLS_SLUG}.md`), controlsPage);

